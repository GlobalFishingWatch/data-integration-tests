def test_parse_argv_handles_both_flag_spellings_and_positionals() -> None:
    parsed = composer.parse_argv([
        "pipe-widgets", "-v", "--project", "example-project", "--table-description",
        "Widgets, all of them", "publish", "--labels=a=1", "--labels=b=2",
        "--offset", "-3", "--wait_for_job",
    ])

    assert parsed.positionals == ("pipe-widgets", "publish")
    assert parsed.flags == (
        composer.Flag("-v", None),
        composer.Flag("--project", "example-project"),
        composer.Flag("--table-description", "Widgets, all of them"),
        composer.Flag("--labels", "a=1"),
        composer.Flag("--labels", "b=2"),
        composer.Flag("--offset", "-3"),
        composer.Flag("--wait_for_job", None),
    )
    assert parsed.names() == ("-v", "--project", "--table-description", "--labels",
                              "--offset", "--wait_for_job")
    assert parsed.values("--labels") == ("a=1", "b=2")
    assert parsed.value("--project") == "example-project"


def test_parse_argv_cannot_tell_a_bare_flag_before_a_positional_without_a_hint() -> None:
    tokens = ["pipe-widgets", "-v", "publish"]

    assert composer.parse_argv(tokens).positionals == ("pipe-widgets",)
    hinted = composer.parse_argv(tokens, bare={"-v"})
    assert hinted.positionals == ("pipe-widgets", "publish")
    assert hinted.flags == (composer.Flag("-v", None),)


def test_parse_argv_treats_everything_after_double_dash_as_positional() -> None:
    parsed = composer.parse_argv(["run", "--x=1", "--", "--not-a-flag", "y"])

    assert parsed.positionals == ("run", "--not-a-flag", "y")
    assert parsed.flags == (composer.Flag("--x", "1"),)


def test_parsed_argv_value_rejects_missing_and_repeated_flags() -> None:
    parsed = composer.parse_argv(["--labels=a", "--labels=b"])

    with pytest.raises(KeyError):
        parsed.value("--project")
    with pytest.raises(ValueError, match="given 2 times"):
        parsed.value("--labels")


def test_diff_flags_compares_names_and_value_multisets() -> None:
    left = composer.parse_argv(["--a=1", "--b=2", "--labels=x", "--labels=y", "--own=l", "--l"])
    right = composer.parse_argv(["--labels=y", "--labels=x", "--a=1", "--b=3", "--own=r", "--r"])

    diff = composer.diff_flags(left, right, ignore={"--own"})

    assert diff == composer.FlagDiff(
        only_left=("--l",), only_right=("--r",), differing=("--b",), same=("--a", "--labels"),
    )
    assert not diff.identical
    assert composer.diff_flags(left, left).identical


