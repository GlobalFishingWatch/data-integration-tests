def _live_commit() -> str | None:
    repo = composer.default_composer_dir()
    if not (repo / ".git").exists():
        return None
    try:
        return composer.resolve_ref(repo, composer.DEFAULT_REF)
    except RuntimeError:
        return None


@pytest.mark.skipif(_live_commit() is None,
                    reason="no composer-dags-production checkout with origin/main")
def test_every_real_snapshot_parses_as_data() -> None:
    """Structure only: values change with production and are not asserted."""
    repo = composer.default_composer_dir()
    commit = _live_commit()
    names = composer.list_snapshots(repo, commit)

    dags = [composer.load_dag(repo, name, commit) for name in names]

    assert names
    assert all(d.commit == commit for d in dags)
    container_tasks = [t for d in dags for t in d.tasks if t.image]
    assert container_tasks
    assert all(isinstance(a, str) for t in container_tasks for a in t.argv)
