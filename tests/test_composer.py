def _git(repo: Path, *args: str) -> str:
    return subprocess.run(["git", "-C", str(repo), *args], check=True,
                          capture_output=True, text=True).stdout


@pytest.fixture
def composer_repo(tmp_path: Path) -> Path:
    """A git repo with the synthetic snapshot committed on ``main``."""
    repo = tmp_path / "composer"
    snapshots = repo / composer.SNAPSHOT_DIR
    snapshots.mkdir(parents=True)
    (snapshots / "example_widgets_v1_backfill.py").write_text(_SNAPSHOT_SOURCE)
    (snapshots / "README.md").write_text("not a snapshot\n")
    _git(repo, "init", "-q", "-b", "main")
    _git(repo, "add", ".")
    _git(repo, "-c", "user.name=t", "-c", "user.email=t@example.invalid",
         "commit", "-q", "-m", "fixture")
    return repo


def test_list_snapshots_returns_the_python_files_at_the_ref(composer_repo: Path) -> None:
    assert composer.list_snapshots(composer_repo, "main") == ("example_widgets_v1_backfill",)


def test_load_dag_reads_the_commit_not_the_working_tree(composer_repo: Path) -> None:
    commit = _git(composer_repo, "rev-parse", "main").strip()
    path = composer_repo / composer.SNAPSHOT_DIR / "example_widgets_v1_backfill.py"
    path.write_text("rendered_dag = {'dag_id': 'uncommitted edit', 'tasks': {}}\n")

    dag = composer.load_dag(composer_repo, "example_widgets_v1_backfill", "main")

    assert dag.commit == commit
    assert dag.snapshot == "example_widgets_v1_backfill"
    assert dag.dag_id == "example.widgets.v1.backfill"


def test_load_dag_reports_a_missing_snapshot_or_ref(composer_repo: Path) -> None:
    with pytest.raises(RuntimeError, match="git show"):
        composer.load_dag(composer_repo, "no_such_dag", "main")
    with pytest.raises(RuntimeError, match="rev-parse"):
        composer.load_dag(composer_repo, "example_widgets_v1_backfill", "no-such-ref")


def test_default_composer_dir_prefers_the_env_var(monkeypatch, tmp_path: Path) -> None:
    monkeypatch.setenv(composer.COMPOSER_DIR_ENV, str(tmp_path / "explicit"))
    monkeypatch.setenv("PROJECTS", str(tmp_path / "projects"))
    assert composer.default_composer_dir() == tmp_path / "explicit"

    monkeypatch.delenv(composer.COMPOSER_DIR_ENV)
    assert composer.default_composer_dir() == tmp_path / "projects" / "composer-dags-production"


def test_cli_prints_a_dags_tasks_as_json(composer_repo: Path) -> None:
    result = CliRunner().invoke(cli.main, [
        "composer-dag", "example_widgets_v1_backfill", "--repo", str(composer_repo),
        "--ref", "main", "--task-prefix", "widgets.b", "--templated",
    ])

    assert result.exit_code == 0, result.output
    out = json.loads(result.output)
    assert out["dag_id"] == "example.widgets.v1.backfill"
    assert out["data_interval"] == ["2026-03-01T00:00:00+00:00", "2026-03-11T00:00:00+00:00"]
    assert [t["task_id"] for t in out["tasks"]] == ["widgets.build"]
    assert "--end_date={end_date}" in out["tasks"][0]["templated_argv"]


def test_cli_reports_an_unreadable_snapshot(composer_repo: Path) -> None:
    result = CliRunner().invoke(cli.main, [
        "composer-dag", "no_such_dag", "--repo", str(composer_repo), "--ref", "main",
    ])

    assert result.exit_code == 1
    assert "git show" in result.output


